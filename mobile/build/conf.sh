#!/bin/sh

export DEZI_DOCKER_GROUP="${DEZI_DOCKER_GROUP:-"docker.fasolti.com.br"}"
export PROJECT_GROUP="${PROJECT_GROUP:-"dezi"}"
export IMAGE_NAME="mobile"
export CI_PROJECT_NAMESPACE="${CI_PROJECT_NAMESPACE:-"avd"}"
export CI_PROJECT_NAME="${CI_PROJECT_NAME:-"mobile"}"

DEZI_MOBILE_BUILDS_DIR="${DEZI_MOBILE_BUILDS_DIR:-${DEZI_BUILDS_DIR:-${BUILDS_DIR:-"dist/apps"}}}"

DEZI_MOBILE_BUILDER_IMAGE_NAME="${DEZI_MOBILE_BUILDER_IMAGE_NAME:-"${BUILDER_IMAGE_NAME:-"docker.fasolti.com.br/ionic-builder"}"}"
DEZI_MOBILE_BUILDER_IMAGE_TAG="${DEZI_MOBILE_BUILDER_IMAGE_TAG:-${BUILDER_IMAGE_TAG:-"1.2.0"}}"
DEZI_MOBILE_BUILDER_IMAGE="${DEZI_MOBILE_BUILDER_IMAGE:-${BUILDER_IMAGE:-"$DEZI_MOBILE_BUILDER_IMAGE_NAME:$DEZI_MOBILE_BUILDER_IMAGE_TAG"}}"

DEZI_MOBILE_ANDROID_KEYSTORE_PASS="${DEZI_MOBILE_ANDROID_KEYSTORE_PASS:-"${KEYSTORE_PASS}"}"
DEZI_MOBILE_ANDROID_KEYSTORE_KEY="${DEZI_MOBILE_ANDROID_KEYSTORE_KEY:-"${KEYSTORE_KEY}"}"
DEZI_MOBILE_ANDROID_KEYSTORE_KEYPASS="${DEZI_MOBILE_ANDROID_KEYSTORE_KEYPASS:-"${KEYSTORE_KEYPASS}"}"

PROJECT_HOME_DIR="dist/.home"
PROJECT_ROOT="${PROJECT_ROOT:-"$( cd "$(dirname "$0")/.."; pwd )"}"
PROJECT_BUILDS_ROOT="$PROJECT_ROOT/$DEZI_MOBILE_BUILDS_DIR"

NODE_IMAGE=${NODE_IMAGE:-"node:lts"}

HOST_HOME="$PROJECT_ROOT/$PROJECT_HOME_DIR"
HOST_M2_DIR="${HOST_HOME}/.m2"
HOST_NPMRC_PATH="${HOST_HOME}/.npmrc"

GUEST_ROOT="/usr/src/dezi-mobile"
GUEST_HOME="$GUEST_ROOT/$PROJECT_HOME_DIR"
GUEST_UNAME="root"
GUEST_UID="$(id -u)"
GUEST_GID="$(id -g)"

GUEST_JAVA_OPTS="-Djava.awt.headless=true -Duser.home=${GUEST_HOME} -Duser.dir=${GUEST_ROOT} -Duser.name=${GUEST_UNAME}"
GUEST_M2_DIR="${GUEST_HOME}/.m2"

GRADLE_OPTS="-Dorg.gradle.daemon=false -Dandroid.enableAapt2=false -Dfile.encoding=utf-8"

DOCKER() {
	# DEZI_MOBILE_ANDROID_KEYSTORE_PASS="${DEZI_MOBILE_ANDROID_KEYSTORE_PASS:?Faltando KEYSTORE_PASS.}"
	# DEZI_MOBILE_ANDROID_KEYSTORE_KEY="${DEZI_MOBILE_ANDROID_KEYSTORE_KEY:?Faltando KEYSTORE_KEY.}"
	# DEZI_MOBILE_ANDROID_KEYSTORE_KEYPASS="${DEZI_MOBILE_ANDROID_KEYSTORE_KEYPASS:?Faltando KEYSTORE_KEYPASS.}"

	docker run \
		--rm \
		--user "${GUEST_UID}:${GUEST_GID}" \
		-e MAVEN_CONFIG="${GUEST_M2_DIR}" \
		-e JAVA_OPTS="${GUEST_JAVA_OPTS}" \
		-e _JAVA_OPTIONS="${GUEST_JAVA_OPTS}" \
		-e HOME="${GUEST_HOME}" \
		-e USER="${GUEST_UNAME}" \
		-e GRADLE_OPTS="${GRADLE_OPTS}" \
		-e DEBUG="${DEBUG}" \
		-e DEZI_ENV="${DEZI_ENV}" \
		-e DEZI_MOBILE_ENV_DEFAULTS="${DEZI_MOBILE_ENV_DEFAULTS}" \
		-e DEZI_MOBILE_ANDROID_KEYSTORE_PASS="${DEZI_MOBILE_ANDROID_KEYSTORE_PASS}" \
		-e DEZI_MOBILE_ANDROID_KEYSTORE_KEY="${DEZI_MOBILE_ANDROID_KEYSTORE_KEY}" \
		-e DEZI_MOBILE_ANDROID_KEYSTORE_KEYPASS="${DEZI_MOBILE_ANDROID_KEYSTORE_KEYPASS}" \
		-e CI_AUTOMATION_ID="${CI_AUTOMATION_ID}" \
		-e CI_AUTOMATION_NAME="${CI_AUTOMATION_NAME}" \
		-e CI_GIT_COMMIT_SHA="${CI_GIT_COMMIT_SHA}" \
		-e CI_GIT_REF="${CI_GIT_REF}" \
		-e CI_JOB_ID="${CI_JOB_ID}" \
		-e CI_JOB_NAME="${CI_JOB_NAME}" \
		-e CI_COMMIT_SHA="${CI_COMMIT_SHA}" \
		-e CI_COMMIT_REF_NAME="${CI_COMMIT_REF_NAME}" \
		-e CI_COMMIT_TAG="${CI_COMMIT_TAG}" \
		-v "${PROJECT_ROOT}:${GUEST_ROOT}" \
		-w "${GUEST_ROOT}" \
		"${DEZI_MOBILE_BUILDER_IMAGE}" \
		"$@"
}

NODE_DOCKER() {
	docker run \
		--rm \
		--user "${GUEST_UID}:${GUEST_GID}" \
		-v "${PROJECT_ROOT}:${GUEST_ROOT}" \
		-w "${GUEST_ROOT}" \
		-e DEZI_ENV="${DEZI_ENV}" \
		-e HOME="${GUEST_HOME}" \
		-e USER="${GUEST_UNAME}" \
		"${NODE_IMAGE}" \
		"$@"
}

mkdir -p "$PROJECT_BUILDS_ROOT"
mkdir -p "$HOST_HOME"
mkdir -p "$HOST_M2_DIR"

if [ ! -e "$HOST_M2_DIR/settings.xml" ]; then
	cp -f "$PROJECT_ROOT/build/settings.xml" "$HOST_M2_DIR/settings.xml"
fi

if [ ! -e "$HOST_NPMRC_PATH" ]; then
	touch "$HOST_NPMRC_PATH"
fi
