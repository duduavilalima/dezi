package br.com.fasolti.avd.transfer;

import br.com.fasolti.avd.transfer.simple.EmpresaSimpleTO;
import br.com.fasolti.avd.transfer.util.BaseAuditedTO;
import br.com.fasolti.avd.types.Situacao;
import br.com.fasolti.commons.client.transfer.SearchObject;
import br.com.fasolti.commons.util.TransactionalObject;

public class UnidadeTO extends BaseAuditedTO implements TransactionalObject<Situacao>, Comparable, SearchObject {

	private String nome;

	private String descricao;

	private UnidadeTO unidadePai;

	private EmpresaSimpleTO empresa;

	private Situacao situacao;

	public String getNome() {
		return nome;
	}

	public void setNome(String nome) {
		this.nome = nome;
	}

	public String getDescricao() {
		return descricao;
	}

	public void setDescricao(String descricao) {
		this.descricao = descricao;
	}

	public UnidadeTO getUnidadePai() {
		return unidadePai;
	}

	public void setUnidadePai(UnidadeTO unidadePai) {
		this.unidadePai = unidadePai;
	}

	public EmpresaSimpleTO getEmpresa() {
		return empresa;
	}

	public void setEmpresa(EmpresaSimpleTO empresa) {
		this.empresa = empresa;
	}

	public Situacao getSituacao() {
		return situacao;
	}

	public void setSituacao(Situacao situacao) {
		this.situacao = situacao;
	}

	@Override
	public int compareTo(Object o) {
		return ((UnidadeTO) o).getNome().compareTo(getNome());
	}

	@Override
	public Situacao getStatus() {
		return situacao;
	}

	@Override
	public void setStatus(Situacao situacao) {
		this.situacao = situacao;
	}
}
